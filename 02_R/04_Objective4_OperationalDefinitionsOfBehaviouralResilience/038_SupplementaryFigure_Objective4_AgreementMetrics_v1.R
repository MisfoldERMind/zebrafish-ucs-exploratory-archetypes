theme_manuscript <- function() {

  ggplot2::theme_classic(
    base_size = 10.5,
    base_family = "Arial"
  ) +
    ggplot2::theme(
      axis.text = ggplot2::element_text(
        colour = "black"
      ),

      plot.background = ggplot2::element_rect(
        fill = "white",
        colour = NA
      ),

      panel.background = ggplot2::element_rect(
        fill = "white",
        colour = NA
      ),

      plot.tag = ggplot2::element_text(
        face = "bold",
        size = 16
      ),

      plot.tag.position = c(
        0.12,
        1
      )
    )
}


# ------------------------------------------------------------
# 9. Helper: matrix to long plotting data
# ------------------------------------------------------------

prepare_heatmap_data <- function(
  matrix_object,
  value_name
) {

  matrix_display <- matrix_object[
    method_order,
    method_order,
    drop = FALSE
  ]

  as.data.frame(
    as.table(
      matrix_display
    ),
    stringsAsFactors = FALSE
  ) %>%
    dplyr::rename(
      Method_x = Var1,
      Method_y = Var2,
      !!value_name := Freq
    ) %>%
    dplyr::mutate(
      x_num = match(
        Method_x,
        method_order
      ),

      y_num = match(
        Method_y,
        rev(method_order)
      )
    )
}


