expected_methods <- c(
  "Swaminathan",
  "PCA_Quantiles",
  "GMM",
  "TwoStep",
  "Louvain"
)

matrix_objects <- list(
  ARI = ari_matrix,
  Cramers_V = cramers_v_matrix,
  Exact_agreement = exact_agreement_matrix
)

for (matrix_name in names(matrix_objects)) {

  matrix_i <- matrix_objects[[matrix_name]]

  if (!is.matrix(matrix_i)) {
    stop(
      matrix_name,
      " object is not a matrix."
    )
  }

  if (
    !all(
      expected_methods %in%
        rownames(matrix_i)
    ) ||
    !all(
      expected_methods %in%
        colnames(matrix_i)
    )
  ) {
    stop(
      matrix_name,
      " matrix does not contain the five expected methods."
    )
  }

  if (
    any(
      !is.finite(
        matrix_i[
          expected_methods,
          expected_methods,
          drop = FALSE
        ]
      )
    )
  ) {
    stop(
      matrix_name,
      " matrix contains missing or non-finite values."
    )
  }
}


