# 11. Heatmap constructor
# ------------------------------------------------------------
# The colour bar is drawn manually inside the same coordinate
# system as each heatmap. This preserves the compact geometry
# established for the final Objective 4 main figure.

make_agreement_heatmap <- function(
  data,
  panel_tag,
  scale_title,
  scale_limits,
  scale_breaks,
  label_digits,
  title_x_offset = 0.30
) {

  if (
    length(scale_limits) != 2L ||
    any(!is.finite(scale_limits)) ||
    scale_limits[1] >= scale_limits[2]
  ) {
    stop(
      "Invalid scale limits supplied to ",
      panel_tag,
      "."
    )
  }

  # Relative fill intensity only controls text colour.
  data <- data %>%
    dplyr::mutate(
      Fill_fraction =
        (
          Value -
            scale_limits[1]
        ) /
        (
          scale_limits[2] -
            scale_limits[1]
        ),

      Text_colour = ifelse(
        Fill_fraction >= 0.58,
        "white",
        "black"
      )
    )

  label_format <- paste0(
    "%.",
    label_digits,
    "f"
  )

  # Geometry reproduced from the final Objective 4 heatmap.
  colourbar_bottom <- 1.45
  colourbar_top <- 3.75
  colourbar_xmin <- 5.64
  colourbar_xmax <- 5.72

  colourbar_edges <- seq(
    colourbar_bottom,
    colourbar_top,
    length.out = 201
  )

  colourbar_values <- seq(
    scale_limits[1],
    scale_limits[2],
    length.out = 200
  )

  colourbar_data <- data.frame(
    xmin = colourbar_xmin,
    xmax = colourbar_xmax,
    ymin = colourbar_edges[
      -length(
        colourbar_edges
      )
    ],
    ymax = colourbar_edges[-1],
    Value = colourbar_values
  )

  colourbar_label_data <- data.frame(
    Value = scale_breaks,
    y =
      colourbar_bottom +
      (
        scale_breaks -
          scale_limits[1]
      ) /
      (
        scale_limits[2] -
          scale_limits[1]
      ) *
      (
        colourbar_top -
          colourbar_bottom
      )
  )

  if (label_digits == 1L) {

    colourbar_label_data$Label <- sprintf(
      "%.0f",
      colourbar_label_data$Value
    )

  } else {

    colourbar_label_data$Label <- sprintf(
      "%.2f",
      colourbar_label_data$Value
    )
  }

  ggplot2::ggplot() +

    ggplot2::geom_tile(
      data = data,
      mapping = ggplot2::aes(
        x = x_num,
        y = y_num,
        fill = Value
      ),
      width = 1,
      height = 1,
      colour = "white",
      linewidth = 0.80
    ) +

    ggplot2::geom_text(
      data = data,
      mapping = ggplot2::aes(
        x = x_num,
        y = y_num,
        label = sprintf(
          label_format,
          Value
        ),
        colour = Text_colour
      ),
      family = "Arial",
      size = 3.45,
      show.legend = FALSE
    ) +

    ggplot2::scale_colour_identity() +

    ggplot2::geom_rect(
      data = colourbar_data,
      mapping = ggplot2::aes(
        xmin = xmin,
        xmax = xmax,
        ymin = ymin,
        ymax = ymax,
        fill = Value
      ),
      inherit.aes = FALSE,
      colour = NA
    ) +

    ggplot2::geom_segment(
      data = colourbar_label_data,
      mapping = ggplot2::aes(
        x = colourbar_xmax,
        xend = colourbar_xmax + 0.05,
        y = y,
        yend = y
      ),
      inherit.aes = FALSE,
      linewidth = 0.35,
      colour = "black"
    ) +

    ggplot2::geom_text(
      data = colourbar_label_data,
      mapping = ggplot2::aes(
        x = colourbar_xmax + 0.08,
        y = y,
        label = Label
      ),
      inherit.aes = FALSE,
      family = "Arial",
      size = 2.65,
      hjust = 0,
      colour = "black"
    ) +

    ggplot2::annotate(
      "text",
      x = (
        colourbar_xmin +
          colourbar_xmax
      ) / 2 + title_x_offset,
      y = colourbar_top + 0.38,
      label = scale_title,
      family = "Arial",
      size = 3.05,
      hjust = 0.5
    ) +

    ggplot2::scale_fill_gradient(
      low = "white",
      high = colour_turquoise,
      limits = scale_limits,
      guide = "none"
    ) +

    ggplot2::scale_x_continuous(
      breaks = 1:5,
      labels = unname(
        method_labels[
          method_order
        ]
      ),
      limits = c(
        0.50,
        6.55
      ),
      expand = c(
        0,
        0
      )
    ) +

    ggplot2::scale_y_continuous(
      breaks = 1:5,
      labels = unname(
        method_labels[
          rev(method_order)
        ]
      ),
      limits = c(
        0.50,
        5.50
      ),
      expand = c(
        0,
        0
      )
    ) +

    ggplot2::coord_fixed(
      ratio = 1,
      clip = "off"
    ) +

    ggplot2::labs(
      tag = panel_tag,
      x = NULL,
      y = NULL
    ) +

    theme_manuscript() +

    ggplot2::theme(
      axis.line = ggplot2::element_blank(),
      axis.ticks = ggplot2::element_blank(),

      axis.text.x = ggplot2::element_text(
        angle = 38,
        hjust = 1,
        vjust = 1,
        size = 8.2
      ),

      axis.text.y = ggplot2::element_text(
        size = 8.2
      ),

      plot.margin = ggplot2::margin(
        t = 4,
        r = 6,
        b = 2,
        l = 0
      )
    )
}


