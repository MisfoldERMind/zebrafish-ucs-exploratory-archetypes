segment_to_integer <- function(x, object_name) {
  if (is.factor(x)) {
    x <- as.character(x)
  }

  x <- trimws(as.character(x))
  x <- sub(
    pattern = "^Cluster[[:space:]]+",
    replacement = "",
    x = x,
    ignore.case = TRUE
  )

  result <- suppressWarnings(as.integer(x))

  if (anyNA(result) || any(!result %in% c(1L, 2L))) {
    stop("Invalid Stress-cluster labels were detected in ", object_name, ".")
  }

  result
}

