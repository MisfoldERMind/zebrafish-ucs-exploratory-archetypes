# ============================================================
# 010_ClusterStability.R
#
# Objective 1
# Bootstrap stability of the k = 45 exploratory Louvain
# segmentation imported from the corrected script 006
#
# Final reference configuration:
# - Robust behavioural space:
#   within Author: (x - median) / (1.4826 x raw MAD)
# - Euclidean distance
# - Similarity = 1 / (1 + distance)
# - Weighted, undirected union kNN graph
# - k = 45
# - Louvain community detection
# - Two reference algorithmic segments
#
# Bootstrap design:
# - Case resampling with replacement
# - 89 bootstrap rows per iteration
# - Fixed robust behavioural space
# - Fixed k = 45
# - Reconstruction of the same weighted graph used in the corrected
#   script 006
#
# Primary stability metric:
# - Adjusted Rand Index (ARI) calculated once per unique
#   original fish represented in the bootstrap sample.
# - When an original fish is sampled more than once, its
#   bootstrap membership is defined by deterministic majority
#   consensus across its resampled copies.
#
# Secondary diagnostic:
# - ARI calculated across all 89 bootstrap rows.
#
# Inputs generated by the corrected:
# 006_Figure4_Louvain.R
# ============================================================

