adjusted_rand_index <- function(
    partition_1,
    partition_2
) {
  partition_1 <- as.integer(partition_1)
  partition_2 <- as.integer(partition_2)
  
  if (length(partition_1) != length(partition_2)) {
    stop(
      "ARI partitions have different lengths."
    )
  }
  
  if (length(partition_1) < 2L) {
    stop(
      "At least two observations are required to calculate ARI."
    )
  }
  
  if (
    anyNA(partition_1) ||
    anyNA(partition_2)
  ) {
    stop(
      "Missing values were detected in an ARI partition."
    )
  }
  
  contingency_table <- table(
    partition_1,
    partition_2
  )
  
  combination_2 <- function(x) {
    x * (x - 1) / 2
  }
  
  sum_cells <- sum(
    combination_2(
      contingency_table
    )
  )
  
  sum_rows <- sum(
    combination_2(
      rowSums(
        contingency_table
      )
    )
  )
  
  sum_columns <- sum(
    combination_2(
      colSums(
        contingency_table
      )
    )
  )
  
  total_pairs <- combination_2(
    sum(
      contingency_table
    )
  )
  
  expected_index <-
    (sum_rows * sum_columns) /
    total_pairs
  
  maximum_index <-
    (sum_rows + sum_columns) /
    2
  
  denominator <-
    maximum_index -
    expected_index
  
  if (
    abs(denominator) <=
    sqrt(.Machine$double.eps)
  ) {
    same_relationships <- identical(
      outer(
        partition_1,
        partition_1,
        `==`
      ),
      outer(
        partition_2,
        partition_2,
        `==`
      )
    )
    
    return(
      if (same_relationships) 1 else 0
    )
  }
  
  ari_value <-
    (sum_cells - expected_index) /
    denominator
  
  if (
    length(ari_value) != 1L ||
    !is.finite(ari_value)
  ) {
    stop(
      "The adjusted Rand index is not finite."
    )
  }
  
  as.numeric(ari_value)
}

partitions_are_equivalent <- function(
    partition_1,
    partition_2
) {
  if (length(partition_1) != length(partition_2)) {
    stop(
      "Partition-equivalence vectors have different lengths."
    )
  }
  
  if (
    anyNA(partition_1) ||
    anyNA(partition_2)
  ) {
    stop(
      "Missing values were detected in a partition-equivalence check."
    )
  }
  
  contingency_table <- table(
    partition_1,
    partition_2
  )
  
  equivalent <- (
    all(
      rowSums(
        contingency_table > 0
      ) == 1L
    ) &&
      all(
        colSums(
          contingency_table > 0
        ) == 1L
      )
  )
  
  isTRUE(equivalent)
}

