    )
  }
}

ari_tolerance <- 1e-10

for (
  ari_column_i in c(
    "ARI_Unique_Fish",
    "ARI_Bootstrap_Rows"
  )
) {
  if (
    any(
      successful_results[[ari_column_i]] <
      -1 - ari_tolerance |
      successful_results[[ari_column_i]] >
      1 + ari_tolerance
    )
  ) {
    stop(
      "At least one value in ",
      ari_column_i,
      " is outside the valid ARI range."
    )
  }
