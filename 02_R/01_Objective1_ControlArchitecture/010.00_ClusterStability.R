# ------------------------------------------------------------
# 12. Exact weighted union-kNN graph constructor
# ------------------------------------------------------------

construct_weighted_union_knn_graph <- function(
    data_matrix,
    k_value,
    vertex_names
) {
  data_matrix <- as.matrix(data_matrix)
  storage.mode(data_matrix) <- "double"
  
  number_of_rows <- nrow(data_matrix)
  number_of_variables <- ncol(data_matrix)
  
  if (
    is.null(number_of_rows) ||
    number_of_rows < 2L
  ) {
    stop(
      "The input matrix must contain at least two rows."
    )
  }
  
  if (
    is.null(number_of_variables) ||
    number_of_variables < 1L
  ) {
    stop(
      "The input matrix contains no behavioural variables."
    )
  }
  
  if (
    length(k_value) != 1L ||
    is.na(k_value) ||
    !is.finite(k_value) ||
    k_value != as.integer(k_value)
  ) {
    stop(
      "k must be one finite integer."
    )
  }
  
  k_value <- as.integer(k_value)
  
  if (
    k_value < 1L ||
    k_value >= number_of_rows
  ) {
    stop(
      "k must be at least one and smaller than the number of rows."
    )
  }
  
  vertex_names <- as.character(vertex_names)
  
  if (length(vertex_names) != number_of_rows) {
    stop(
      "There must be one vertex name per matrix row."
    )
  }
  
  if (
    anyNA(vertex_names) ||
    any(vertex_names == "") ||
    anyDuplicated(vertex_names) > 0L
  ) {
    stop(
      "Vertex names must be non-missing, non-empty, and unique."
    )
  }
  
  if (any(!is.finite(data_matrix))) {
    stop(
      "The input matrix contains missing or non-finite values."
    )
  }
  
  # Euclidean distance matrix.
  
  distance_matrix <- as.matrix(
    stats::dist(
      data_matrix,
      method = "euclidean",
      diag = TRUE,
      upper = TRUE
    )
  )
  
  if (
    !identical(
      dim(distance_matrix),
      c(number_of_rows, number_of_rows)
    )
  ) {
    stop(
      "The Euclidean distance matrix has incorrect dimensions."
    )
  }
  
  if (
    any(!is.finite(distance_matrix)) ||
    any(distance_matrix < 0)
  ) {
    stop(
      "The Euclidean distance matrix contains invalid values."
    )
  }
  
  # Exclude only each row's self-distance. Distinct bootstrap
  # rows representing the same original fish may legitimately
  # have distance zero.
  
  diag(distance_matrix) <- Inf
  
  index_tie_breaker <- seq_len(number_of_rows)
  
  nearest_neighbour_index <- matrix(
    NA_integer_,
    nrow = number_of_rows,
    ncol = k_value
  )
  
  for (row_i in seq_len(number_of_rows)) {
    neighbour_order <- order(
      distance_matrix[row_i, ],
      index_tie_breaker,
      na.last = NA
    )
    
    if (length(neighbour_order) < k_value) {
      stop(
        "Fewer than k valid neighbours were available for row ",
        row_i,
        "."
      )
    }
    
    nearest_neighbour_index[row_i, ] <-
      neighbour_order[
        seq_len(k_value)
      ]
  }
  
  if (anyNA(nearest_neighbour_index)) {
    stop(
      "Missing nearest-neighbour indices were generated."
    )
  }
  
  from_index <- rep(
    seq_len(number_of_rows),
    each = k_value
  )
  
  to_index <- as.vector(
    t(
      nearest_neighbour_index
    )
  )
  
  neighbour_distance <- distance_matrix[
    cbind(
      from_index,
      to_index
    )
  ]
  
  if (any(from_index == to_index)) {
    stop(
      "Self-neighbour relationships were detected."
    )
  }
  
  if (
    any(!is.finite(neighbour_distance)) ||
    any(neighbour_distance < 0)
  ) {
    stop(
      "Invalid nearest-neighbour distances were generated."
    )
  }
  
  edge_list_directed <- tibble::tibble(
    From_Index = from_index,
    To_Index = to_index,
    From_ID = vertex_names[from_index],
    To_ID = vertex_names[to_index],
    Neighbour_Rank = rep(
      seq_len(k_value),
      times = number_of_rows
    ),
    Distance = neighbour_distance,
    Similarity = 1 / (1 + neighbour_distance)
  )
  
  if (
    nrow(edge_list_directed) !=
    number_of_rows * k_value
  ) {
    stop(
      "The directed kNN relation table has an incorrect number of rows."
    )
  }
  
  if (
    any(!is.finite(edge_list_directed$Similarity)) ||
    any(edge_list_directed$Similarity <= 0)
  ) {
    stop(
      "Invalid similarity weights were generated."
    )
  }
  
  # Convert directed kNN relations to the weighted,
  # undirected union graph used in script 006.
  
  edge_list_undirected <- edge_list_directed %>%
    dplyr::mutate(
      Undirected_From =
        pmin(From_Index, To_Index),
      Undirected_To =
        pmax(From_Index, To_Index)
    ) %>%
    dplyr::group_by(
      Undirected_From,
      Undirected_To
    ) %>%
    dplyr::summarise(
      Distance = mean(Distance),
      weight = mean(Similarity),
      Directed_Relations = dplyr::n(),
      .groups = "drop"
    ) %>%
    dplyr::mutate(
      from = vertex_names[Undirected_From],
      to = vertex_names[Undirected_To],
      .before = 1
    ) %>%
    dplyr::select(
      from,
      to,
      weight,
      Distance,
      Directed_Relations,
      Undirected_From,
      Undirected_To
    )
  
  if (nrow(edge_list_undirected) < 1L) {
    stop(
      "The undirected edge list contains no edges."
    )
  }
  
  if (any(edge_list_undirected$from == edge_list_undirected$to)) {
    stop(
      "Self-loops remained after symmetrising the kNN graph."
    )
  }
  
  if (
    any(!is.finite(edge_list_undirected$weight)) ||
    any(edge_list_undirected$weight <= 0)
  ) {
    stop(
      "The undirected edge list contains invalid weights."
    )
  }
  
  vertices <- tibble::tibble(
    name = vertex_names
  )
  
  graph_knn <- igraph::graph_from_data_frame(
    d = edge_list_undirected %>%
      dplyr::select(
        from,
        to,
        weight,
        Distance,
        Directed_Relations
      ),
    directed = FALSE,
    vertices = vertices
  )
  
  if (igraph::is_directed(graph_knn)) {
    stop(
      "The reconstructed kNN graph is directed."
    )
  }
  
  if (
    igraph::vcount(graph_knn) !=
    number_of_rows
  ) {
    stop(
      "The reconstructed graph does not contain one vertex per row."
    )
  }
  
  if (
    !identical(
      igraph::V(graph_knn)$name,
      vertex_names
    )
  ) {
    stop(
      "Graph vertices are not in the expected row order."
    )
  }
  
  if (
    igraph::ecount(graph_knn) !=
    nrow(edge_list_undirected)
  ) {
    stop(
      "The graph edge count does not match the undirected edge list."
    )
  }
  
  edge_weights <- igraph::E(graph_knn)$weight
  
  if (
    is.null(edge_weights) ||
    length(edge_weights) !=
    igraph::ecount(graph_knn) ||
    any(!is.finite(edge_weights)) ||
    any(edge_weights <= 0)
  ) {
    stop(
      "The reconstructed graph contains invalid edge weights."
    )
  }
  
  vertex_degrees <- igraph::degree(
    graph_knn
  )
  
  if (any(vertex_degrees < 1L)) {
    stop(
      "At least one graph vertex is isolated."
    )
  }
  
  list(
    graph = graph_knn,
    directed_relations = edge_list_directed,
    undirected_edges = edge_list_undirected
  )
}

