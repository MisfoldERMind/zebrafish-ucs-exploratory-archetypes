    From = pmin(
      as.character(edge_table$from),
      as.character(edge_table$to)
    ),
    To = pmax(
      as.character(edge_table$from),
      as.character(edge_table$to)
    ),
    weight = as.numeric(edge_table$weight)
  ) %>%
    dplyr::arrange(From, To)

  if (
    anyNA(canonical_table) ||
    any(!is.finite(canonical_table$weight)) ||
    any(canonical_table$weight <= 0) ||
    anyDuplicated(canonical_table[c("From", "To")]) > 0L
  ) {
    stop("A reference graph contains invalid weighted edges.")
  }

  canonical_table
}

