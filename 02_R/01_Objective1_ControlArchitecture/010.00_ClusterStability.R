# 15. Function for one bootstrap iteration
# ------------------------------------------------------------

run_bootstrap_iteration <- function(
    iteration,
    data_matrix,
    reference_partition,
    k_value,
    bootstrap_seed_value,
    louvain_seed_value
) {
  tryCatch({
    
    data_matrix <- as.matrix(data_matrix)
    storage.mode(data_matrix) <- "double"
    
    number_of_rows <- nrow(data_matrix)
    
    if (
      length(reference_partition) !=
      number_of_rows
    ) {
      stop(
        "The reference partition does not contain one ",
        "membership per original fish."
      )
    }
    
    iteration_bootstrap_seed <-
      as.integer(
        bootstrap_seed_value +
          iteration -
          1L
      )
    
    iteration_louvain_seed <-
      as.integer(
        louvain_seed_value +
          iteration -
          1L
      )
    
    # Case-bootstrap sample.
    
    set.seed(iteration_bootstrap_seed)
    
    bootstrap_indices <- sample.int(
      n = number_of_rows,
      size = number_of_rows,
      replace = TRUE
    )
    
    if (
      length(bootstrap_indices) !=
      number_of_rows
    ) {
      stop(
        "The bootstrap sample has an incorrect size."
      )
    }
    
    bootstrap_matrix <- data_matrix[
      bootstrap_indices,
      ,
      drop = FALSE
    ]
    
    bootstrap_reference_rows <-
      reference_partition[
        bootstrap_indices
      ]
    
    bootstrap_vertex_names <- sprintf(
      "B%04d_R%03d",
      iteration,
      seq_len(number_of_rows)
    )
    
    rownames(bootstrap_matrix) <-
      bootstrap_vertex_names
    
    # Reconstruct the exact weighted graph.
    
    graph_result <-
      construct_weighted_union_knn_graph(
        data_matrix = bootstrap_matrix,
        k_value = k_value,
        vertex_names = bootstrap_vertex_names
      )
    
    graph_bootstrap <-
      graph_result$graph
    
    edge_weights <-
      igraph::E(graph_bootstrap)$weight
    
    # Weighted Louvain community detection.
    
    set.seed(iteration_louvain_seed)
    
    louvain_bootstrap <- igraph::cluster_louvain(
      graph = graph_bootstrap,
      weights = edge_weights
    )
    
    bootstrap_membership_rows <- as.integer(
      igraph::membership(
        louvain_bootstrap
      )
    )
    
    names(bootstrap_membership_rows) <-
      igraph::V(graph_bootstrap)$name
    
    bootstrap_membership_rows <-
      bootstrap_membership_rows[
        bootstrap_vertex_names
      ]
    
    if (
      length(bootstrap_membership_rows) !=
      number_of_rows ||
      anyNA(bootstrap_membership_rows)
    ) {
      stop(
        "The bootstrap membership could not be aligned ",
        "with the bootstrap rows."
      )
    }
    
    bootstrap_cluster_count <- length(
      unique(
        bootstrap_membership_rows
      )
    )
    
    if (bootstrap_cluster_count < 1L) {
      stop(
        "The bootstrap iteration produced no clusters."
      )
    }
    
    # Secondary ARI: all bootstrap rows, including repeated copies.
    
    ari_bootstrap_rows <- adjusted_rand_index(
      bootstrap_reference_rows,
      bootstrap_membership_rows
    )
    
    # Primary ARI: one consensus assignment per unique original fish.
    #
    # Each original fish may appear one or more times in the
    # bootstrap sample. Its consensus membership is the modal
    # Louvain cluster among its copies. Ties are resolved
    # deterministically by choosing the smallest numeric label.
    # ARI itself is invariant to label numbering.
    
    membership_split <- split(
      bootstrap_membership_rows,
      bootstrap_indices
    )
    
    unique_original_indices <- as.integer(
      names(
        membership_split
      )
    )
    
    numeric_order <- order(
      unique_original_indices
    )
    
    unique_original_indices <-
      unique_original_indices[
        numeric_order
      ]
    
    membership_split <-
      membership_split[
        numeric_order
      ]
    
    copy_counts <- vapply(
      membership_split,
      length,
      integer(1)
    )
    
    consensus_membership <- vapply(
      membership_split,
      function(cluster_values) {
        cluster_counts <- table(
          cluster_values
        )
        
        modal_labels <- as.integer(
          names(
            cluster_counts[
              cluster_counts ==
                max(cluster_counts)
            ]
          )
        )
        
        min(modal_labels)
      },
      integer(1)
    )
    
    tied_consensus <- vapply(
      membership_split,
      function(cluster_values) {
        cluster_counts <- table(
          cluster_values
        )
        
        sum(
          cluster_counts ==
            max(cluster_counts)
        ) > 1L
      },
      logical(1)
    )
    
    copy_consistency <- vapply(
      membership_split,
      function(cluster_values) {
        cluster_counts <- table(
          cluster_values
        )
        
        max(cluster_counts) /
          length(cluster_values)
      },
      numeric(1)
    )
    
    reference_unique <-
      reference_partition[
        unique_original_indices
      ]
    
    if (
      length(reference_unique) !=
      length(consensus_membership)
    ) {
      stop(
        "The unique-fish reference and consensus partitions ",
        "have different lengths."
      )
    }
    
    ari_unique_fish <- adjusted_rand_index(
      reference_unique,
      consensus_membership
    )
    
    repeated_fish <- copy_counts > 1L
    number_of_repeated_fish <- sum(repeated_fish)
    
    if (number_of_repeated_fish > 0L) {
      mean_repeated_copy_consistency <- mean(
        copy_consistency[
          repeated_fish
        ]
      )
      
      minimum_repeated_copy_consistency <- min(
        copy_consistency[
          repeated_fish
        ]
      )
    } else {
      mean_repeated_copy_consistency <- 1
      minimum_repeated_copy_consistency <- 1
    }
    
    graph_components <- igraph::components(
      graph_bootstrap
    )
    
    weighted_modularity <- igraph::modularity(
      x = graph_bootstrap,
      membership =
        bootstrap_membership_rows[
          igraph::V(graph_bootstrap)$name
        ],
      weights = edge_weights,
      directed = FALSE
    )
    
    if (!is.finite(weighted_modularity)) {
      stop(
        "Bootstrap weighted modularity is not finite."
      )
    }
    
    bootstrap_cluster_sizes <- as.integer(
      table(
        bootstrap_membership_rows
      )
    )
    
    tibble::tibble(
      Iteration = as.integer(iteration),
      Success = TRUE,
      ARI_Unique_Fish = ari_unique_fish,
      ARI_Bootstrap_Rows = ari_bootstrap_rows,
      Unique_original_fish =
        length(unique_original_indices),
      Repeated_original_fish =
        number_of_repeated_fish,
      Tied_consensus_assignments =
        sum(tied_consensus),
      Mean_repeated_copy_consistency =
        mean_repeated_copy_consistency,
      Minimum_repeated_copy_consistency =
        minimum_repeated_copy_consistency,
      Reference_clusters_present =
        length(unique(reference_unique)),
      Bootstrap_clusters =
        bootstrap_cluster_count,
      Two_cluster_solution =
        bootstrap_cluster_count ==
        expected_number_of_clusters,
      Vertices =
        igraph::vcount(graph_bootstrap),
      Directed_kNN_relations =
        nrow(graph_result$directed_relations),
      Edges =
        igraph::ecount(graph_bootstrap),
      Graph_density =
        igraph::edge_density(
          graph_bootstrap,
          loops = FALSE
        ),
      Mean_degree =
        mean(
          igraph::degree(
            graph_bootstrap
          )
        ),
      Connected_components =
        graph_components$no,
      Connected =
        igraph::is_connected(
          graph_bootstrap
        ),
      Weighted_modularity =
        as.numeric(weighted_modularity),
      Minimum_cluster_size =
        min(bootstrap_cluster_sizes),
      Maximum_cluster_size =
        max(bootstrap_cluster_sizes),
      Bootstrap_seed =
        iteration_bootstrap_seed,
      Louvain_seed =
        iteration_louvain_seed,
      Error_Message =
        NA_character_
    )
    
  }, error = function(error_condition) {
    
    tibble::tibble(
      Iteration = as.integer(iteration),
      Success = FALSE,
      ARI_Unique_Fish = NA_real_,
      ARI_Bootstrap_Rows = NA_real_,
      Unique_original_fish = NA_integer_,
      Repeated_original_fish = NA_integer_,
      Tied_consensus_assignments = NA_integer_,
      Mean_repeated_copy_consistency = NA_real_,
      Minimum_repeated_copy_consistency = NA_real_,
      Reference_clusters_present = NA_integer_,
      Bootstrap_clusters = NA_integer_,
      Two_cluster_solution = NA,
      Vertices = NA_integer_,
      Directed_kNN_relations = NA_integer_,
      Edges = NA_integer_,
      Graph_density = NA_real_,
      Mean_degree = NA_real_,
      Connected_components = NA_integer_,
      Connected = NA,
      Weighted_modularity = NA_real_,
      Minimum_cluster_size = NA_integer_,
      Maximum_cluster_size = NA_integer_,
      Bootstrap_seed =
        as.integer(
          bootstrap_seed_value +
            iteration -
            1L
        ),
      Louvain_seed =
        as.integer(
          louvain_seed_value +
            iteration -
            1L
        ),
      Error_Message =
        conditionMessage(
          error_condition
        )
    )
  })
}

