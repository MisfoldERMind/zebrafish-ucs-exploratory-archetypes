scalar_integer <- function(
    x,
    object_name
) {
  if (
    length(x) != 1L ||
    is.na(x) ||
    !is.finite(x) ||
    x != as.integer(x)
  ) {
    stop(
      object_name,
      " must contain one finite integer."
    )
  }
  
  as.integer(x)
}

