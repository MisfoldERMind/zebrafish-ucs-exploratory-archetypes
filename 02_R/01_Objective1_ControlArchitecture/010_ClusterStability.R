robust_variable_audit <- dplyr::bind_rows(lapply(
  unique(control_louvain$Author),
  function(author_i) {
    author_data <- control_louvain[
      control_louvain$Author == author_i,
      ,
      drop = FALSE
    ]

    dplyr::bind_rows(lapply(
      robust_variables,
      function(variable_i) {
        values_i <- author_data[[variable_i]]

        tibble::tibble(
          Author = author_i,
          Variable = variable_i,
          n = length(values_i),
          Median = stats::median(values_i),
          Scaled_MAD = stats::mad(
            values_i,
            center = stats::median(values_i),
            constant = 1.4826
          )
        )
      }
    ))
  }
))

audit_tolerance <- 1e-6

if (
  any(
    abs(
      robust_variable_audit$Median
    ) > audit_tolerance
  )
) {
  stop(
    "At least one within-Author robust variable does not have a ",
    "median approximately equal to zero."
  )
}

