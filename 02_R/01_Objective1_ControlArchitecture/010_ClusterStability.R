scalar_integer <- function(
    x,
    object_name
) {
  if (
    length(x) != 1L ||
    is.na(x) ||
    !is.finite(x) ||
    x != as.integer(x)
  ) {
    stop(
      object_name,
      " must contain one finite integer."
    )
  }
  
  as.integer(x)
}

scalar_numeric <- function(
    x,
    object_name
) {
  if (
    length(x) != 1L ||
    is.na(x) ||
    !is.finite(x)
  ) {
    stop(
      object_name,
      " must contain one finite numeric value."
    )
  }
  
  as.numeric(x)
}

scalar_character <- function(
    x,
    object_name
) {
  if (
    length(x) != 1L ||
    is.na(x) ||
    !nzchar(as.character(x))
  ) {
    stop(
      object_name,
      " must contain one non-empty character value."
    )
  }
  
  as.character(x)
}

