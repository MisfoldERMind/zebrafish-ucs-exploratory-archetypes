  crossing_rz = "Line\ncrossings",
  top_entry_rz = "Upper-zone\nentries",
  top_time_rz = "Upper-zone\ntime"
)

panel_b_individual <- control_louvain %>%
  dplyr::select(
    ID,
    Cluster,
    Profile,
    dplyr::all_of(robust_variables)
  ) %>%
  tidyr::pivot_longer(
    cols = dplyr::all_of(robust_variables),
    names_to = "Robust_Variable",
    values_to = "Robust_Z_Score"
  ) %>%
  dplyr::mutate(
    Variable = factor(
      unname(variable_keys[Robust_Variable]),
      levels = unname(variable_keys),
      ordered = TRUE
    ),
    Variable_Index = as.integer(Variable)
  )

if (
  nrow(panel_b_individual) != expected_n * length(robust_variables) ||
  anyNA(panel_b_individual$Variable) ||
  any(!is.finite(panel_b_individual$Robust_Z_Score))
) {
  stop("Panel B individual data failed the integrity audit.")
}

panel_b_summary <- panel_b_individual %>%
  dplyr::group_by(Cluster, Profile, Variable, Variable_Index) %>%
  dplyr::summarise(
    n = dplyr::n(),
    Median = stats::median(Robust_Z_Score),
    Q1 = as.numeric(
      stats::quantile(
        Robust_Z_Score,
        probs = 0.25,
        names = FALSE,
        type = 7
      )
    ),
    Q3 = as.numeric(
      stats::quantile(
        Robust_Z_Score,
        probs = 0.75,
        names = FALSE,
        type = 7
      )
    ),
    .groups = "drop"
  ) %>%
  dplyr::mutate(
    Median_Label = sprintf("%.2f", Median),
    Label_Y = dplyr::if_else(
      Profile == profile_levels[[1]],
      Q3 + 0.15,
      Q1 - 0.15
    ),
    Label_Vjust = dplyr::if_else(
      Profile == profile_levels[[1]],
      0,
      1
    )
  ) %>%
  dplyr::arrange(Cluster, Variable_Index)

if (
  nrow(panel_b_summary) != expected_clusters * length(robust_variables) ||
  any(!is.finite(as.matrix(
    panel_b_summary[c("Median", "Q1", "Q3", "Label_Y")]
  )))
) {
  stop("Panel B summary data failed the integrity audit.")
}

y_lower <- min(c(panel_b_summary$Q1, 0)) - 0.35
y_upper <- max(c(panel_b_summary$Q3, 0)) + 0.35

