# Verify that the loaded object comes from the definitive
# within-Author robust normalisation, rather than from the
# invalidated global normalisation.

robust_audit <- dplyr::bind_rows(
  lapply(
    sort(unique(control_louvain$Author)),
    function(author_i) {
      author_rows <- control_louvain$Author == author_i

      dplyr::bind_rows(
        lapply(
          robust_variables,
          function(variable_i) {
            values <- control_louvain[[variable_i]][author_rows]
            centre <- stats::median(values)

            tibble::tibble(
              Author = author_i,
              Variable = variable_i,
              n = length(values),
              Median = centre,
              Scaled_MAD = stats::mad(
                values,
                center = centre,
                constant = 1.4826
              )
            )
          }
        )
      )
    }
  )
)

normalisation_tolerance <- 1e-6

if (
  nrow(robust_audit) != expected_author_n * length(robust_variables) ||
  any(abs(robust_audit$Median) > normalisation_tolerance) ||
  any(abs(robust_audit$Scaled_MAD - 1) > normalisation_tolerance)
) {
  stop(
    "The behavioural object does not pass the definitive within-Author ",
