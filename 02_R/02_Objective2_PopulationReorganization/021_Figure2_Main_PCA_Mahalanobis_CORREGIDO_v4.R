#
# Main Figure 2
#
# Panel A
#   Control and Stress populations projected into the corrected
#   Control-derived PC1-PC2 space, with 95% normal-theory data
#   ellipses and group centroids.
#
#   A single asterisk is printed above the Stress centroid as a
#   call to the figure legend.
#
#   IMPORTANT:
#   - D4D = 1.264 is NOT recalculated here.
#   - No D4D text is printed inside the panel.
#   - No arrow is printed inside the panel.
#   - The already established PERMANOVA result should be reported
#     in the figure legend:
#       F(1,173) = 8.10; R2 = 0.0423; p = 0.0016.
#
# Panel B
#   Mahalanobis distance to the pooled normative Control atlas,
#   using the definitive individual distances generated by the
#   corrected Script 015.
#
#   Control fish retain their leave-one-out reference distances;
#   Stress fish retain their distances to the complete Control atlas.
#   No Mahalanobis distance or inferential statistic is recalculated.
#
# Definitive upstream dependencies:
#   - corrected Script 020:
#       objective2_control_stress_pca_ellipses95_results.rds
#   - corrected Script 015:
#       objective2_mahalanobis_normative_atlas_results_robust.rds
